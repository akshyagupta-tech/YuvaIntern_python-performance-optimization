import unittest
from data_cruncher_slow import find_duplicates_slow
from data_cruncher_fast import OptimizedDataEngine

class TestOptimizationEquivalence(unittest.TestCase):

    def test_duplicate_algorithm_equivalence(self):
        """Verify hash-set O(N) duplicate finder matches O(N^2) results exactly."""
        sample_dataset = [10, 5, 2, 10, 8, 3, 5, 100, 2, 999]
        legacy_result = sorted(find_duplicates_slow(sample_dataset))
        optimized_result = sorted(OptimizedDataEngine.find_duplicates_linear(sample_dataset))
        self.assertEqual(legacy_result, optimized_result)

    def test_empty_payload_tolerance(self):
        """Verify engine operates predictably on empty sequences."""
        self.assertEqual(OptimizedDataEngine.find_duplicates_linear([]), [])
        self.assertEqual(OptimizedDataEngine.buffer_stream_concatenation(0), 1)

    def test_no_duplicate_integrity(self):
        """Verify dataset without duplicates yields empty list."""
        unique_data = [1, 2, 3, 4, 5, 6, 7, 8, 9]
        self.assertEqual(OptimizedDataEngine.find_duplicates_linear(unique_data), [])

    def test_string_buffer_length_consistency(self):
        """Verify string length generated by join matches standard expectations."""
        length = OptimizedDataEngine.buffer_stream_concatenation(100)
        self.assertGreater(length, 100)

if __name__ == "__main__":
    unittest.main()
